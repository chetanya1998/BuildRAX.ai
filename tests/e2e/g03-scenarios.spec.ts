import { expect, test } from "@playwright/test";
import { generateInspectAndOpen, installGenerationJobFixture } from "./generation-job-fixture";

for (const theme of ["light", "dark"] as const) test(`scenario save, read-only playback and recovery in ${theme}`, async ({ page, isMobile }, testInfo) => {
  await page.addInitScript((value) => localStorage.setItem("buildrax-theme", value), theme);
  await page.emulateMedia({ reducedMotion: theme === "dark" ? "reduce" : "no-preference" });
  await installGenerationJobFixture(page);
  await page.goto("/start?template=multi-tenant-saas");
  await generateInspectAndOpen(page);
  const calls: string[] = [];
  page.on("request", (request) => { if (/\/api\/v1\/(ai|generation-jobs)/.test(request.url())) calls.push(request.url()); });
  await page.getByRole("button", { name: "Open scenarios", exact: true }).click();
  await page.getByRole("button", { name: /Save suggested scenarios/ }).click();
  const choices = page.getByLabel("Scenario", { exact: true });
  await expect(choices.locator("option")).toHaveCount(4);
  if (isMobile) await page.keyboard.press("Control+z");
  else await page.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(choices.locator("option")).toHaveCount(1);
  if (isMobile) await page.keyboard.press("Control+Shift+z");
  else await page.getByRole("button", { name: "Redo", exact: true }).click();
  await expect(choices.locator("option")).toHaveCount(4);
  await choices.selectOption({ index: 1 });
  await expect(page.getByLabel("Browser recovery status")).toContainText("Saved locally");
  const viewport = page.locator(".react-flow__viewport");
  const before = await viewport.getAttribute("style");
  await page.getByRole("button", { name: "Play scenario", exact: true }).click();
  await page.getByRole("button", { name: "Pause scenario", exact: true }).click();
  await expect(page.getByTestId("scenario-status")).toContainText("paused · Step 1");
  await expect(page.getByLabel("Diagram title")).toHaveAttribute("readonly", "");
  await expect(page.locator(`[data-scenario-pulse="${theme === "dark" ? 0 : 1}"]`)).toHaveCount(2);
  await expect(page.getByRole("button", { name: "Auto layout", exact: true })).toHaveCount(0);
  const count = await page.locator(".react-flow__node-semantic").count();
  await page.keyboard.press("Delete");
  await expect(page.locator(".react-flow__node-semantic")).toHaveCount(count);
  await page.getByRole("button", { name: "Next step", exact: true }).click();
  await expect(page.getByTestId("scenario-status")).toContainText("Step 2");
  await page.getByRole("button", { name: "Previous step", exact: true }).click();
  await page.getByRole("button", { name: "Restart scenario", exact: true }).click();
  await expect(page.getByTestId("scenario-status")).toContainText("paused · Step 1");
  await page.screenshot({ path: testInfo.outputPath(`g03-${theme}.png`) });
  if (isMobile) await page.getByRole("button", { name: "Exit playback", exact: true }).click();
  else await page.keyboard.press("Escape");
  await expect(page.getByTestId("scenario-status")).toHaveText("idle");
  await expect(viewport).toHaveAttribute("style", before!);
  await expect(page.locator("[data-scenario-pulse]")).toHaveCount(0);
  await page.reload();
  await page.getByRole("button", { name: "Open scenarios", exact: true }).click();
  await expect(page.getByLabel("Scenario", { exact: true }).locator("option")).toHaveCount(4);
  await expect(page.getByTestId("scenario-status")).toHaveText("idle");
  expect(calls).toEqual([]);
});
